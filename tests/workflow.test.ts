import { beforeAll, afterAll, beforeEach, afterEach, describe, it, expect, vi } from "vitest";
import { PGlite } from "@electric-sql/pglite";
import { PDFDocument, PDFPage } from "pdf-lib";
import { priceQuote } from "../src/lib/pricing";
import { embeddedDatabase, type Database } from "../src/lib/db";
import { schema } from "../src/lib/schema";
import { createOrder, confirmSupplier, releaseInvoices, markDelivered, getOrder, type DocumentRow, type MailRow } from "../src/lib/orders";
import { drainOutbox } from "../src/lib/mail";
import { buildPdf } from "../src/lib/pdf";
import { fixture } from "./fixtures";
import { legalTexts } from "../src/lib/legal";

const sendMail = vi.hoisted(() => vi.fn());
vi.mock("nodemailer", () => ({ default: { createTransport: () => ({ sendMail }) } }));
let client: PGlite, db: Database;
beforeAll(async () => { client = new PGlite(); await client.exec(schema); db = embeddedDatabase(client); });
afterAll(async () => { await client.close(); });
beforeEach(() => {
  vi.stubEnv("SELLER_TAX_ID", "DE-TEST-CONFIGURATION");
  vi.stubEnv("SELLER_IBAN", "TEST-IBAN-NOT-A-BANK-ACCOUNT");
  vi.stubEnv("SMTP_HOST", "smtp.example.invalid"); vi.stubEnv("SMTP_USER", "test"); vi.stubEnv("SMTP_PASSWORD", "test");
  vi.stubEnv("ADMIN_EMAIL", "admin@example.invalid");
  vi.stubEnv("ORDER_NOTIFICATION_EMAIL", "");
  vi.stubEnv("MAIL_MODE", "smtp"); sendMail.mockReset(); sendMail.mockResolvedValue({ accepted: ["test@example.invalid"], rejected: [] });
});
afterEach(() => { vi.unstubAllEnvs(); vi.restoreAllMocks(); });
describe("persistent PostgreSQL order lifecycle", () => {
  it("queues one additional order notification without changing the admin login or duplicating retries", async () => {
    vi.stubEnv("ORDER_NOTIFICATION_EMAIL", "orders@example.invalid");
    const { order: input, quote } = fixture();
    const order = await createOrder(db, input, quote);
    await createOrder(db, input, quote);
    const mails = await db.query<MailRow>("SELECT * FROM outbox WHERE order_id=$1 ORDER BY position", [order.id]);
    expect(mails.map(mail => mail.recipient)).toEqual([input.participants[0].email, "admin@example.invalid", "orders@example.invalid"]);
    expect(mails[2].body).toBe(mails[1].body);
    expect(mails[2].subject).toBe(mails[1].subject);
    expect(process.env.ADMIN_EMAIL).toBe("admin@example.invalid");
    expect(await drainOutbox(db, 3, order.id)).toEqual({ sent: 3, failed: 0, pending: 0 });
    vi.stubEnv("ORDER_NOTIFICATION_EMAIL", "ADMIN@example.invalid");
    const next = fixture();
    const deduplicated = await createOrder(db, next.order, next.quote);
    expect(await drainOutbox(db, 3, deduplicated.id)).toEqual({ sent: 2, failed: 0, pending: 0 });
    vi.stubEnv("ORDER_NOTIFICATION_EMAIL", "not-an-email");
    const invalid = fixture();
    await expect(createOrder(db, invalid.order, invalid.quote)).rejects.toThrow("ungültig konfiguriert");
  });
  it("runs order → thanks emails → supplier confirmation → three invoice PDFs → delivery notes and correct due dates", async () => {
    const { order: input, quote } = fixture([10, 8, 5]);
    const order = await createOrder(db, input, quote);
    expect(order.status).toBe("ordered");
    expect(order.snapshot.termsText).toBe(legalTexts().terms);
    expect(order.snapshot.privacyText).toBe(legalTexts().privacy);
    expect(order.snapshot.legalVersion).toBe(input.legalVersion);
    expect(order.snapshot.paymentWithoutDiscount).toBe(true);
    expect((await db.query("SELECT * FROM outbox WHERE order_id=$1", [order.id])).length).toBe(4);
    await expect(releaseInvoices(db, order.id, "admin")).rejects.toThrow("Lieferantenbestätigung");
    await expect(markDelivered(db, order.id, [quote.createdOn], "admin")).rejects.toThrow("Rechnungsfreigabe");
    expect(await drainOutbox(db, 4, order.id)).toEqual({ sent: 4, failed: 0, pending: 0 });
    expect(sendMail).toHaveBeenCalledTimes(4);
    expect(sendMail.mock.calls[3][0].to).toBe("admin@example.invalid");
    expect(sendMail.mock.calls[3][0].text).toContain(`/admin/bestellungen/${order.id}`);
    expect(sendMail.mock.calls[0][0].text).toContain("14 Tage nach tatsächlicher Lieferung");
    expect(sendMail.mock.calls[0][0].text).toContain("Zahlbar ohne Abzug. Kein Skonto.");
    expect(sendMail.mock.calls[0][0].text).toContain("Wir stimmen die Lieferung mit Ihnen ab.");
    expect(sendMail.mock.calls[0][0].text).toContain("Auftragsbestätigung und Rechnung per E-Mail");
    expect(sendMail.mock.calls[0][0].text).not.toContain("manuell freigegeben");
    expect(sendMail.mock.calls[0][0].text).not.toContain("Wir bestellen beziehungsweise disponieren");
    expect(sendMail.mock.calls[0][0].text).toContain("Gesamt netto inkl. Lieferung:");
    expect(sendMail.mock.calls[0][0].text).not.toContain("01523-6183155");
    expect(sendMail.mock.calls[0][0].text).not.toMatch(/\bundefined\b/);
    expect(sendMail.mock.calls[0][0].text).not.toMatch(/\n(?:Warenwert|Lieferkosten) netto:/);
    expect(sendMail.mock.calls[0][0].text).toContain(order.snapshot.termsText);
    expect(sendMail.mock.calls[0][0].text).not.toContain("Lieferant");
    await confirmSupplier(db, order.id, "SUPPLIER-TEST-42", "admin");
    expect((await getOrder(db, order.id)).status).toBe("supplier_confirmed");
    await releaseInvoices(db, order.id, "admin");
    await expect(releaseInvoices(db, order.id, "admin")).rejects.toThrow();
    const invoices = await db.query<DocumentRow>("SELECT * FROM documents WHERE order_id=$1 AND kind='invoice' ORDER BY participant_index", [order.id]);
    expect(invoices).toHaveLength(3);
    expect(invoices.every(invoice => invoice.snapshot.paymentWithoutDiscount)).toBe(true);
    expect(invoices.every(invoice => invoice.snapshot.invoiceDesign === "brand-v1")).toBe(true);
    expect(new Set(invoices.map(invoice => invoice.number)).size).toBe(3);
    expect(invoices.reduce((sum, invoice) => sum + invoice.snapshot.line.grossCents, 0)).toBe(quote.grossCents);
    const drawText = vi.spyOn(PDFPage.prototype, "drawText");
    const buffer = await buildPdf(invoices[0]);
    const invoiceText = drawText.mock.calls.map(([text]) => text).join("\n");
    expect(invoiceText).toContain("Gesamt netto inkl. Lieferung:");
    expect(invoiceText).toContain("Zahlbar ohne Abzug. Kein Skonto.");
    expect(invoiceText).not.toMatch(/Lieferkosten netto|Warenwert netto|Einzelpreis netto/);
    drawText.mockRestore();
    expect(buffer.subarray(0, 5).toString()).toBe("%PDF-");
    const loadedInvoice = await PDFDocument.load(buffer);
    expect(loadedInvoice.getPageCount()).toBe(1);
    expect(loadedInvoice.getPages()[0].node.Resources()?.toString()).toContain("/XObject");
    expect(await drainOutbox(db, 3, order.id)).toEqual({ sent: 3, failed: 0, pending: 0 });
    expect(sendMail.mock.calls.at(-1)![0].attachments[0].filename).toMatch(/^R-.*\.pdf$/);
    expect(sendMail.mock.calls.at(-1)![0].text).toContain("Hiermit nehmen wir Ihr Angebot");
    expect(sendMail.mock.calls.at(-1)![0].text).toContain("wir bestätigen Ihre Bestellung");
    expect(sendMail.mock.calls.at(-1)![0].text).not.toContain("Lieferant");
    expect(sendMail.mock.calls.at(-1)![0].text).toContain("Zahlbar ohne Abzug. Kein Skonto.");
    expect(sendMail.mock.calls.at(-1)![0].text).toContain(order.snapshot.termsText);
    await markDelivered(db, order.id, input.participants.map(() => quote.createdOn), "admin");
    expect((await getOrder(db, order.id)).status).toBe("delivered");
    expect(await drainOutbox(db, 3, order.id)).toEqual({ sent: 3, failed: 0, pending: 0 });
    expect(sendMail.mock.calls.at(-1)![0].text).toContain("Zahlbar ohne Abzug. Kein Skonto.");
    const notes = await db.query<DocumentRow>("SELECT * FROM documents WHERE order_id=$1 AND kind='delivery'", [order.id]);
    expect(notes).toHaveLength(3);
    expect(notes.every(note => note.snapshot.paymentWithoutDiscount)).toBe(true);
    expect(notes[0].snapshot.invoiceNumber).toMatch(/^R-/);
    await expect(markDelivered(db, order.id, [quote.createdOn], "admin")).rejects.toThrow();
    const filtered = await db.query("SELECT * FROM orders WHERE ($1='' OR status=$1) AND ($2='' OR number ILIKE $3 OR (snapshot->'participants')::text ILIKE $3)", ["delivered", "Winterdienst", "%Winterdienst%"]);
    expect(filtered.length).toBeGreaterThan(0);
  });
  it("preserves the original price presentation of historical invoice snapshots", async () => {
    const { order: input, quote } = fixture();
    const order = await createOrder(db, input, quote);
    await confirmSupplier(db, order.id, "legacy-test", "admin");
    await releaseInvoices(db, order.id, "admin");
    expect(await drainOutbox(db, 3, order.id)).toEqual({ sent: 3, failed: 0, pending: 0 });
    const [invoice] = await db.query<DocumentRow>("SELECT * FROM documents WHERE order_id=$1 AND kind='invoice'", [order.id]);
    delete invoice.snapshot.line.deliveryIncluded;
    delete invoice.snapshot.paymentWithoutDiscount;
    delete invoice.snapshot.invoiceDesign;
    expect(invoice.snapshot.seller).not.toHaveProperty("phone");
    if (!invoice.snapshot.seller) throw new Error("The new invoice seller snapshot is missing.");
    Object.assign(invoice.snapshot.seller, { phone: "HISTORICAL-SELLER-PHONE" });
    const drawText = vi.spyOn(PDFPage.prototype, "drawText");
    await buildPdf(invoice);
    const text = drawText.mock.calls.map(([text]) => text).join("\n");
    expect(text).toContain("Warenwert netto:");
    expect(text).toContain("Lieferkosten netto");
    expect(text).toContain("HISTORICAL-SELLER-PHONE");
    expect(text).not.toContain("Kein Skonto");
  });
  it("deduplicates retried orders and refuses reuse with changed customer data", async () => {
    const { order: input, quote } = fixture();
    const one = await createOrder(db, input, quote);
    const retry = await createOrder(db, input, quote);
    expect(one.id).toBe(retry.id);
    expect((await db.query("SELECT * FROM outbox WHERE order_id=$1", [one.id]))).toHaveLength(2);
    await expect(createOrder(db, { ...input, participants: [{ ...input.participants[0], company: "Changed" }] }, quote)).rejects.toThrow("anderen Daten");
  });
  it("persists two differently loaded trucks in one order and one invoice, with both products on delivery documents", async () => {
    const base = fixture([46]);
    const items = [{ product: "bigbag" as const, tonnes: 23 }, { product: "bags" as const, tonnes: 23 }];
    const quote = priceQuote({ ...base.input, items }, { metres: 1500125, states: ["RP"], labels: ["Mainz"] });
    const input = { ...base.order, items };
    const order = await createOrder(db, input, quote);
    expect(order.snapshot.items).toEqual(items);
    expect((await createOrder(db, input, quote)).id).toBe(order.id);
    await expect(createOrder(db, { ...input, items: [{ ...items[0], tonnes: 46 }, items[1]] }, quote)).rejects.toThrow("anderen Daten");
    expect(await drainOutbox(db, 2, order.id)).toEqual({ sent: 2, failed: 0, pending: 0 });
    expect(sendMail.mock.calls[0][0].text).toContain("23 Tonnen Streusalz im BigBag");
    expect(sendMail.mock.calls[0][0].text).toContain("23 Tonnen Streusalz in 25-kg-Säcken");
    await confirmSupplier(db, order.id, "mixed-load-confirmed", "admin");
    await releaseInvoices(db, order.id, "admin");
    const invoices = await db.query<DocumentRow>("SELECT * FROM documents WHERE order_id=$1 AND kind='invoice'", [order.id]);
    expect(invoices).toHaveLength(1);
    expect(invoices[0].snapshot.items).toEqual(quote.items);
    expect(invoices[0].snapshot.line.netCents).toBe(1750050);
    const drawText = vi.spyOn(PDFPage.prototype, "drawText");
    await buildPdf(invoices[0]);
    let text = drawText.mock.calls.map(([value]) => value).join("\n");
    expect(text).toContain("23 Tonnen Streusalz im BigBag");
    expect(text).toContain("23 Tonnen Streusalz in 25-kg-Säcken");
    expect(text).toContain("23 BigBags mit je 1.000 kg");
    expect(text).toContain("920 Säcke");
    expect(text.match(/Inklusive Lieferung/g)).toHaveLength(2);
    expect(text).not.toContain("Lieferkosten netto");
    expect(text).toContain("Kein Skonto");
    await drainOutbox(db, 1, order.id);
    await markDelivered(db, order.id, [quote.createdOn], "admin");
    const [note] = await db.query<DocumentRow>("SELECT * FROM documents WHERE order_id=$1 AND kind='delivery'", [order.id]);
    drawText.mockClear();
    await buildPdf(note);
    text = drawText.mock.calls.map(([value]) => value).join("\n");
    expect(text).toContain("23 Tonnen Streusalz im BigBag");
    expect(text).toContain("23 Tonnen Streusalz in 25-kg-Säcken");
    await drainOutbox(db, 1, order.id);
  });
  it("reports SMTP failure, persists retry state and sends the same message ID on retry", async () => {
    const { order: input, quote } = fixture();
    const order = await createOrder(db, input, quote);
    // Finish pending mails from the preceding test before simulating a failure.
    await drainOutbox(db, 6);
    await db.query("UPDATE outbox SET status='pending',attempts=0 WHERE order_id=$1 AND recipient=$2", [order.id, input.participants[0].email]);
    sendMail.mockRejectedValueOnce(new Error("Test SMTP unavailable"));
    expect(await drainOutbox(db, 1, order.id)).toEqual({ sent: 0, failed: 1, pending: 1 });
    const [failed] = await db.query<MailRow>("SELECT * FROM outbox WHERE order_id=$1 AND recipient=$2", [order.id, input.participants[0].email]);
    expect(failed.status).toBe("failed"); expect(failed.last_error).toContain("SMTP");
    const failedId = sendMail.mock.calls.at(-1)![0].messageId;
    expect(await drainOutbox(db, 1, order.id)).toEqual({ sent: 1, failed: 0, pending: 0 });
    expect(sendMail.mock.calls.at(-1)![0].messageId).toBe(failedId);
    expect((await db.query<MailRow>("SELECT * FROM outbox WHERE id=$1", [failed.id]))[0].status).toBe("sent");
  });
  it("rejects missing seller data and impossible delivery dates without changing order status", async () => {
    const { order: input, quote } = fixture();
    const order = await createOrder(db, input, quote);
    await confirmSupplier(db, order.id, "confirmed", "admin");
    vi.stubEnv("SELLER_TAX_ID", "");
    await expect(releaseInvoices(db, order.id, "admin")).rejects.toThrow("Steuerangabe");
    expect((await getOrder(db, order.id)).status).toBe("supplier_confirmed");
    vi.stubEnv("SELLER_TAX_ID", "TEST");
    await releaseInvoices(db, order.id, "admin");
    for (const dates of [[], ["2099-01-01"], ["2026-02-30"], ["2000-01-01"]]) await expect(markDelivered(db, order.id, dates, "admin")).rejects.toThrow("Lieferdatum");
    expect((await getOrder(db, order.id)).status).toBe("invoiced");
  });
  it("keeps receipt, invoice and delivery email in order and reports pending mail after retry exhaustion", async () => {
    const { order: input, quote } = fixture();
    const order = await createOrder(db, input, quote);
    await drainOutbox(db, 6, order.id);
    await confirmSupplier(db, order.id, "test", "admin");
    await releaseInvoices(db, order.id, "admin");
    await markDelivered(db, order.id, [quote.createdOn], "admin");
    await db.query("UPDATE outbox SET status='failed',attempts=5 WHERE order_id=$1 AND document_id IS NULL AND recipient=$2", [order.id, input.participants[0].email]);
    expect(await drainOutbox(db, 6, order.id)).toEqual({ sent: 0, failed: 0, pending: 3 });
    await db.query("UPDATE outbox SET status='pending',attempts=0 WHERE order_id=$1 AND document_id IS NULL AND recipient=$2", [order.id, input.participants[0].email]);
    const start = sendMail.mock.calls.length;
    expect(await drainOutbox(db, 6, order.id)).toEqual({ sent: 3, failed: 0, pending: 0 });
    expect(sendMail.mock.calls.slice(start).map(call => call[0].subject)).toEqual([
      expect.stringContaining("Vielen Dank"), expect.stringContaining("Rechnung"), expect.stringContaining("Lieferschein"),
    ]);
  });
  it("supports extended Latin and Cyrillic names in real PDF documents", async () => {
    const { order: input, quote } = fixture();
    input.participants[0].contact = "Łukasz Иванов";
    const order = await createOrder(db, input, quote);
    await confirmSupplier(db, order.id, "unicode-test", "admin");
    await releaseInvoices(db, order.id, "admin");
    const [invoice] = await db.query<DocumentRow>("SELECT * FROM documents WHERE order_id=$1", [order.id]);
    expect((await PDFDocument.load(await buildPdf(invoice))).getPageCount()).toBeGreaterThan(0);
  });
  it("rejects a stale legal version before storing an order or queueing customer emails", async () => {
    const { order: input, quote } = fixture();
    vi.stubEnv("TERMS_TEXT", "Changed contract terms for this test");
    await expect(createOrder(db, input, quote)).rejects.toThrow("Vertrags- oder Datenschutzhinweise wurden geändert");
    expect(await db.query("SELECT id FROM orders WHERE request_id=$1", [input.requestId])).toHaveLength(0);
  });
});
